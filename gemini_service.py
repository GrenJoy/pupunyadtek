        new_schedule = json.loads(cleaned_json)
        
        # ВАЖНО: Gemini всегда возвращает ПОЛНЫЙ график со всеми группами
        # Если группа не упомянута в посте - она скопирована из старого графика
        # Если группа упомянута - она обновлена по правилам
        
